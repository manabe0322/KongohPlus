#' pick_al_size
#'
#' @description The function to pick up allele sizes
#' @param dt_exp_one The data.table of the experimental data of one sample with 'setindex' for Marker
#' @param dt_gt_one The data.table of the genotype data of one sample with 'setindex' for Marker
#' @param markers_all All markers
#' @param at_all_mk Analytical thresholds of all markers
#' @param dye_all_mk Dyes of all markers
#' @param index_exp_peak Column indices of peaks in the experimental data
#' @param index_exp_size Column indices of sizes in the experimental data
#' @param index_exp_height Column indices of heights in the experimental data
#' @param index_gt_allele Column indices of alleles in the genotype data
pick_al_size <- function(dt_exp_one, dt_gt_one, markers_all, at_all_mk, dye_all_mk, index_exp_peak, index_exp_size, index_exp_height, index_gt_allele){
  al_mk <- al_peak <- al_size <- al_dye <- numeric(0)
  name_dt_exp <- names(dt_exp_one)
  n_mk_all <- length(markers_all)

  for(i in 1:n_mk_all){
    # Extract data of one marker
    mk <- markers_all[i]
    dt_exp_one_mk <- dt_exp_one[mk]
    peaks <- as.character(dt_exp_one_mk[, index_exp_peak, with = FALSE])
    sizes <- as.numeric(dt_exp_one_mk[, index_exp_size, with = FALSE])
    heights <- as.numeric(dt_exp_one_mk[, index_exp_height, with = FALSE])

    # Remove NA
    index_not_na <- which(!is.na(peaks))
    peaks <- peaks[index_not_na]
    sizes <- sizes[index_not_na]
    heights <- heights[index_not_na]

    # Remove peaks below AT
    index_above_at <- which(heights >= at_all_mk[mk])
    peaks <- peaks[index_above_at]
    sizes <- sizes[index_above_at]
    heights <- heights[index_above_at]

    # Extract the genotype of one marker
    dt_gt_one_mk <- dt_gt_one[mk]
    gt <- as.character(dt_gt_one_mk[, index_gt_allele, with = FALSE])

    # Extract information on the allele
    index_al <- which(is.element(peaks, gt))
    n_al <- length(index_al)
    al_mk <- c(al_mk, rep(mk, n_al))
    al_peak <- c(al_peak, peaks[index_al])
    al_size <- c(al_size, sizes[index_al])
    al_dye <- c(al_dye, rep(dye_all_mk[mk], n_al))
  }

  # Make the output object
  al_size_info <- rbind(al_peak, al_size, al_dye)
  colnames(al_size_info) <- al_mk

  # Return
  return(al_size_info)
}

#' remove_same_bin
#'
#' @description The function to remove two or more peaks which are located in the same bin
#' @param peaks A character vector of peaks
#' @param sizes A numeric vector of sizes
#' @param heights A numeric vector of heights
remove_same_bin <- function(peaks, sizes, heights){

  # Count the number of peaks in each
  count_peak <- table(peaks)

  # Indices of two or more peaks which are located in the same bin
  index_multi <- which(count_peak != 1)

  # Remove two or more peaks which are located in the same bin
  if(length(index_multi) > 0){
    index_cut <- which(is.element(peaks, names(count_peak)[index_multi]))
    peaks <- peaks[-index_cut]
    sizes <- sizes[-index_cut]
    heights <- heights[-index_cut]
  }

  return(list("peaks" = peaks,
              "sizes" = sizes,
              "heights" = heights))
}

#' remove_pu
#'
#' @description The function to remove pull-up peaks
#' @param peaks A character vector of peaks
#' @param sizes A numeric vector of sizes
#' @param heights A numeric vector of heights
#' @param A character vector of the genotype in one marker
#' @param dye Dye of one locus
#' @param al_size Allele sizes generated by the function "pick_al_size"
#' @param al_dye Allele dyes generated by the function "pick_al_size"
#' @param pu_dist The maximum distance between a pull-up peak and the parent allele
remove_pu <- function(peaks, sizes, heights, gt, dye, al_size, al_dye, pu_dist){

  # Indices of alleles
  index_al <- which(is.element(peaks, gt))

  # Extract the sizes of the parent alleles
  index_parent <- which(al_dye != dye)
  sizes_pu <- al_size[index_parent]

  # Indices of pull-up peaks
  index_pu <- numeric(0)

  for(i in 1:length(peaks)){

    # Peaks other than alleles
    if(!is.element(i, index_al)){

      # Extract a size
      sz <- sizes[i]

      # Update indices of pull-up peaks
      if(length(which(abs(sz - sizes_pu) <= pu_dist)) != 0){
        index_pu <- c(index_pu, i)
      }
    }
  }

  # Remove pull-up peaks
  if(length(index_pu) > 0){
    peaks <- peaks[-index_pu]
    sizes <- sizes[-index_pu]
    heights <- heights[-index_pu]
  }

  return(list("peaks" = peaks,
              "sizes" = sizes,
              "heights" = heights))
}

#' arrange_exp_data
#'
#' @description The function to arrange the experimental data
#' @param dt_exp The data.table of the experimental data
#' @param dt_gt The data.table of the genotype data
#' @param markers_auto Autosomal markers
#' @param sr_consider_auto Information on consideration of back, forward, double-back, and minus 2-nt stutters in autosomal markers
#' @param markers_all All markers
#' @param at_all_mk Analytical thresholds of all markers
#' @param dye_all_mk Dyes of all markers
#' @param pu_remove TRUE or FALSE (whether pull-up peaks are automatically removed or not)
#' @param pu_dist The maximum distance between a pull-up peak and the parent allele
arrange_exp_data <- function(dt_exp, dt_gt,
                             markers_auto, sr_consider_auto,
                             markers_all, at_all_mk, dye_all_mk,
                             pu_remove, pu_dist){
  peak_list <- size_list <- height_list <- gt_list <- list()

  name_dt_exp <- names(dt_exp)
  index_exp_peak <- grep("Allele", name_dt_exp)
  index_exp_size <- grep("Size", name_dt_exp)
  index_exp_height <- grep("Height", name_dt_exp)
  sample_names <- unique(dt_exp[, SampleName])

  name_dt_gt <- names(dt_gt)
  index_gt_allele <- grep("Allele", name_dt_gt)

  n_mk_auto <- length(markers_auto)

  setindex(dt_exp, SampleName)
  setindex(dt_gt, SampleName)

  for(i in 1:length(sample_names)){
    dt_exp_one <- dt_exp[SampleName == sample_names[i]]
    dt_gt_one <- dt_gt[SampleName == sample_names[i]]
    setindex(dt_exp_one, Marker)
    setindex(dt_gt_one, Marker)

    # Pick up allele sizes
    if(pu_remove){
      al_size_info <- pick_al_size(dt_exp_one, dt_gt_one, markers_all, at_all_mk, dye_all_mk, index_exp_peak, index_exp_size, index_exp_height, index_gt_allele)
      al_size <- as.numeric(al_size_info[2, ])
      al_dye <- al_size_info[3, ]
    }else{
      al_size <- numeric(0)
      al_dye <- character(0)
    }

    # Define objects for one sample
    peak_list_one <- size_list_one <- height_list_one <- list()
    gt_one <- matrix(NA, nrow = n_mk_auto, ncol = 2)
    rownames(gt_one) <- markers_auto
    colnames(gt_one) <- c("Allele1", "Allele2")

    for(j in 1:n_mk_auto){
      # Extract data of one marker
      mk <- markers_auto[j]
      dt_exp_one_mk <- dt_exp_one[Marker == mk]
      peaks <- as.character(dt_exp_one_mk[, index_exp_peak, with = FALSE])
      sizes <- as.numeric(dt_exp_one_mk[, index_exp_size, with = FALSE])
      heights <- as.numeric(dt_exp_one_mk[, index_exp_height, with = FALSE])

      # Remove NA
      index_not_na <- which(!is.na(peaks))
      peaks <- peaks[index_not_na]
      sizes <- sizes[index_not_na]
      heights <- heights[index_not_na]

      # Remove peaks below AT
      index_above_at <- which(heights >= at_all_mk[mk])
      peaks <- peaks[index_above_at]
      sizes <- sizes[index_above_at]
      heights <- heights[index_above_at]

      # Extract the genotype of one marker
      dt_gt_one_mk <- dt_gt_one[Marker == mk]
      gt <- as.character(dt_gt_one_mk[, index_gt_allele, with = FALSE])
      gt_one[j, ] <- gt

      # Make detectable peaks in the profile under the genotype
      cand_peak <- make_cand_peak(as.numeric(gt), c(sr_consider_auto[mk, ]))

      index_use <- which(is.element(peaks, as.character(cand_peak)))
      if(length(index_use) > 0){
        peaks_use <- peaks[index_use]
        sizes_use <- sizes[index_use]
        heights_use <- heights[index_use]

        # Remove two or more peaks which are located in the same bin
        tmp <- remove_same_bin(peaks_use, sizes_use, heights_use)
        peaks_use <- tmp$peaks
        sizes_use <- tmp$sizes
        heights_use <- tmp$heights

        # Remove pull-up peaks
        if(pu_remove){
          tmp <- remove_pu(peaks_use, sizes_use, heights_use, gt, dye_all_mk[mk], al_size, al_dye, pu_dist)
          peaks_use <- tmp$peaks
          sizes_use <- tmp$sizes
          heights_use <- tmp$heights
        }

        peak_list_one[[j]] <- peaks_use
        size_list_one[[j]] <- sizes_use
        height_list_one[[j]] <- heights_use
      }else{
        peak_list_one[[j]] <- character(0)
        size_list_one[[j]] <- numeric(0)
        height_list_one[[j]] <- numeric(0)
      }
    }

    names(peak_list_one) <- names(size_list_one) <- names(height_list_one) <- markers_auto
    peak_list[[i]] <- peak_list_one
    size_list[[i]] <- size_list_one
    height_list[[i]] <- height_list_one
    gt_list[[i]] <- gt_one
  }

  names(peak_list) <- names(size_list) <- names(height_list) <- names(gt_list) <- sample_names
  return(list("peak_list" = peak_list,
              "size_list" = size_list,
              "height_list" = height_list,
              "gt_list" = gt_list))
}
