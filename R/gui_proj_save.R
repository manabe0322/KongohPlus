#' save_proj_ui
#'
#' @description The function to create the ui module for saving the project
save_proj_ui <- function(id){
  ns <- NS(id)

  tabPanel("Save project",
           useShinyjs(),
           useWaiter(),
           h2("Save project"),
           br(),
           textInput(ns("name_proj"), label = "Enter the project name", value = NULL),
           br(),
           downloadButton(ns("download_proj"), label = "Save as", class = "btn btn-primary btn-lg")
  )
}

#' save_proj_server
#'
#' @description The function to create the server module for saving the project
save_proj_server <- function(id, rv_deconvo, rv_lr, rv_hd_true_random, rv_hd_true_importance){
  moduleServer(
    id,
    function(input, output, session){
      # Data for deconvolution
      data_deconvo <- rv_deconvo$data_deconvo

      # Data for LR
      if(is.null(rv_lr$dt_lr_calc_record)){
        data_lr <- NULL
      }else{
        data_lr <- list(dt_ref = rv_lr$dt_ref, fn_ref = rv_lr$fn_ref, lr_list = rv_lr$lr_list, dt_lr_calc_record = rv_lr$dt_lr_calc_record)
      }

      # Data for Hd true test (random genotypes)
      if(is.null(rv_hd_true_random$lr_rand)){
        hd_true_random <- NULL
      }else{
        hd_true_random <- list(lr_rand = rv_hd_true_random$lr_rand)
      }

      # Data for Hd true test (genotypes generated by importance sampling)
      if(is.null(rv_hd_true_importance$lr_importance)){
        hd_true_importance <- NULL
      }else{
        hd_true_importance <- list(lr_importance = rv_hd_true_importance$lr_importance, bias = rv_hd_true_importance$bias, expect_lr_hd = rv_hd_true_importance$expect_lr_hd)
      }

      output$download_proj <- downloadHandler(
        filename = function(){
          if(isTruthy(input$name_proj)){
            paste0(input$name_proj, ".RData")
          }else{
            paste0(gsub(" ", "_", format(as.POSIXct(Sys.time()), "%Y-%m-%d %H%M%S")), "_KongohPlus_project.RData")
          }
        },

        content = function(file){
          waiter_show(html = spin_3k(), color = "white")
          save(list = c("data_deconvo",
                        "data_lr",
                        "hd_true_random",
                        "hd_true_importance"),
               file = file)
          waiter_hide()
        }
      )
    }
  )
}
